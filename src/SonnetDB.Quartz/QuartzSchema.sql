CREATE TABLE IF NOT EXISTS QRTZ_JOB_DETAILS (
    SCHED_NAME STRING NOT NULL,
    JOB_NAME STRING NOT NULL,
    JOB_GROUP STRING NOT NULL,
    DESCRIPTION STRING,
    JOB_CLASS_NAME STRING NOT NULL,
    IS_DURABLE BOOL NOT NULL,
    IS_NONCONCURRENT BOOL NOT NULL,
    IS_UPDATE_DATA BOOL NOT NULL,
    REQUESTS_RECOVERY BOOL NOT NULL,
    JOB_DATA BLOB,
    PRIMARY KEY (SCHED_NAME, JOB_NAME, JOB_GROUP)
);

CREATE TABLE IF NOT EXISTS QRTZ_TRIGGERS (
    SCHED_NAME STRING NOT NULL,
    TRIGGER_NAME STRING NOT NULL,
    TRIGGER_GROUP STRING NOT NULL,
    JOB_NAME STRING NOT NULL,
    JOB_GROUP STRING NOT NULL,
    DESCRIPTION STRING,
    NEXT_FIRE_TIME INT,
    PREV_FIRE_TIME INT,
    PRIORITY INT,
    TRIGGER_STATE STRING NOT NULL,
    TRIGGER_TYPE STRING NOT NULL,
    START_TIME INT NOT NULL,
    END_TIME INT,
    CALENDAR_NAME STRING,
    MISFIRE_INSTR INT,
    MISFIRE_ORIG_FIRE_TIME INT,
    EXECUTION_GROUP STRING,
    JOB_DATA BLOB,
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    FOREIGN KEY (SCHED_NAME, JOB_NAME, JOB_GROUP)
        REFERENCES QRTZ_JOB_DETAILS (SCHED_NAME, JOB_NAME, JOB_GROUP)
);

CREATE TABLE IF NOT EXISTS QRTZ_SIMPLE_TRIGGERS (
    SCHED_NAME STRING NOT NULL,
    TRIGGER_NAME STRING NOT NULL,
    TRIGGER_GROUP STRING NOT NULL,
    REPEAT_COUNT INT NOT NULL,
    REPEAT_INTERVAL INT NOT NULL,
    TIMES_TRIGGERED INT NOT NULL,
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS QRTZ_CRON_TRIGGERS (
    SCHED_NAME STRING NOT NULL,
    TRIGGER_NAME STRING NOT NULL,
    TRIGGER_GROUP STRING NOT NULL,
    CRON_EXPRESSION STRING NOT NULL,
    TIME_ZONE_ID STRING,
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS QRTZ_SIMPROP_TRIGGERS (
    SCHED_NAME STRING NOT NULL,
    TRIGGER_NAME STRING NOT NULL,
    TRIGGER_GROUP STRING NOT NULL,
    STR_PROP_1 STRING,
    STR_PROP_2 STRING,
    STR_PROP_3 STRING,
    INT_PROP_1 INT,
    INT_PROP_2 INT,
    LONG_PROP_1 INT,
    LONG_PROP_2 INT,
    DEC_PROP_1 DECIMAL,
    DEC_PROP_2 DECIMAL,
    BOOL_PROP_1 BOOL,
    BOOL_PROP_2 BOOL,
    TIME_ZONE_ID STRING,
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS QRTZ_BLOB_TRIGGERS (
    SCHED_NAME STRING NOT NULL,
    TRIGGER_NAME STRING NOT NULL,
    TRIGGER_GROUP STRING NOT NULL,
    BLOB_DATA BLOB,
    PRIMARY KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
    FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS QRTZ_CALENDARS (
    SCHED_NAME STRING NOT NULL,
    CALENDAR_NAME STRING NOT NULL,
    CALENDAR BLOB NOT NULL,
    PRIMARY KEY (SCHED_NAME, CALENDAR_NAME)
);

CREATE TABLE IF NOT EXISTS QRTZ_PAUSED_TRIGGER_GRPS (
    SCHED_NAME STRING NOT NULL,
    TRIGGER_GROUP STRING NOT NULL,
    PRIMARY KEY (SCHED_NAME, TRIGGER_GROUP)
);

CREATE TABLE IF NOT EXISTS QRTZ_PAUSED_JOB_GRPS (
    SCHED_NAME STRING NOT NULL,
    JOB_GROUP STRING NOT NULL,
    PAUSE_REASON STRING,
    PAUSED_BY STRING,
    PAUSED_AT INT,
    PRIMARY KEY (SCHED_NAME, JOB_GROUP)
);

CREATE TABLE IF NOT EXISTS QRTZ_FIRED_TRIGGERS (
    SCHED_NAME STRING NOT NULL,
    ENTRY_ID STRING NOT NULL,
    TRIGGER_NAME STRING NOT NULL,
    TRIGGER_GROUP STRING NOT NULL,
    INSTANCE_NAME STRING NOT NULL,
    FIRED_TIME INT NOT NULL,
    SCHED_TIME INT NOT NULL,
    PRIORITY INT NOT NULL,
    STATE STRING NOT NULL,
    JOB_NAME STRING,
    JOB_GROUP STRING,
    IS_NONCONCURRENT BOOL NOT NULL,
    REQUESTS_RECOVERY BOOL,
    EXECUTION_GROUP STRING,
    PRIMARY KEY (SCHED_NAME, ENTRY_ID)
);

CREATE TABLE IF NOT EXISTS QRTZ_SCHEDULER_STATE (
    SCHED_NAME STRING NOT NULL,
    INSTANCE_NAME STRING NOT NULL,
    LAST_CHECKIN_TIME INT NOT NULL,
    CHECKIN_INTERVAL INT NOT NULL,
    PRIMARY KEY (SCHED_NAME, INSTANCE_NAME)
);

CREATE TABLE IF NOT EXISTS QRTZ_LOCKS (
    SCHED_NAME STRING NOT NULL,
    LOCK_NAME STRING NOT NULL,
    PRIMARY KEY (SCHED_NAME, LOCK_NAME)
);

CREATE INDEX IF NOT EXISTS IDX_QRTZ_T_ACQUIRE ON QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_STATE, NEXT_FIRE_TIME);
CREATE INDEX IF NOT EXISTS IDX_QRTZ_T_JOB ON QRTZ_TRIGGERS (SCHED_NAME, JOB_NAME, JOB_GROUP);
CREATE INDEX IF NOT EXISTS IDX_QRTZ_FT_TRIGGER ON QRTZ_FIRED_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP);
CREATE INDEX IF NOT EXISTS IDX_QRTZ_FT_JOB ON QRTZ_FIRED_TRIGGERS (SCHED_NAME, JOB_NAME, JOB_GROUP);
CREATE INDEX IF NOT EXISTS IDX_QRTZ_FT_INSTANCE ON QRTZ_FIRED_TRIGGERS (SCHED_NAME, INSTANCE_NAME);
